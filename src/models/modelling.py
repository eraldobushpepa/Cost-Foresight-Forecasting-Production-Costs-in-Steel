def load_and_prepare_data(file_paths):
    """
    Charge la target (Y) et toutes les features (X1–X12),
    les aligne sur le même index trimestriel 'PeriodEndDate',
    sélectionne les bonnes colonnes et retourne un DataFrame fusionné.

    C'est ici que je standardise les noms des variables pour la suite du pipeline.
    """
    print("--- 1. Loading & Preparing Data ---")

    all_dfs = []

    # --- 1a. Target (Y) : Cost per Ton ---
    target_df = pd.read_csv(file_paths["target"], parse_dates=["QuarterEnd"])
    target_df = target_df.set_index("QuarterEnd")

    # Je renomme la colonne cible en Y_Cost_Per_Ton pour ne plus dépendre
    # du nom original dans le CSV.
    target_df = target_df.rename(columns={"Cost_Per_Ton": "Y_Cost_Per_Ton"})
    all_dfs.append(target_df)
    print(f"Loaded Target (Y): Y_Cost_Per_Ton from {file_paths['target']}")

    # --- 1b. Core features X1–X3 ---

    # X1 – Scrap PPI
    df_x1 = pd.read_csv(file_paths["X1"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x1 = df_x1[["PCU33123312"]].rename(columns={"PCU33123312": "X1_Scrap_Price"})
    all_dfs.append(df_x1)

    # X2 – Industrial electricity price
    df_x2 = pd.read_csv(file_paths["X2"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x2 = df_x2[["industrial cents per kilowatthour"]].rename(
        columns={"industrial cents per kilowatthour": "X2_Electricity_Price"}
    )
    all_dfs.append(df_x2)

    # X3 – Henry Hub natural gas
    df_x3 = pd.read_csv(file_paths["X3"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x3 = df_x3[
        ["Henry Hub Natural Gas Spot Price Dollars per Million Btu"]
    ].rename(
        columns={
            "Henry Hub Natural Gas Spot Price Dollars per Million Btu": "X3_Natural_Gas_Price"
        }
    )
    all_dfs.append(df_x3)

    print("Loaded Core Features: X1, X2, X3")

    # --- 1c. Advanced features X4–X12 ---

    # X4 – Diesel price (transport)
    df_x4 = pd.read_csv(file_paths["X4"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x4 = df_x4[
        ["U.S. No 2 Diesel Ultra Low Sulfur (0-15 ppm) Retail Prices Dollars per Gallon"]
    ].rename(
        columns={
            "U.S. No 2 Diesel Ultra Low Sulfur (0-15 ppm) Retail Prices Dollars per Gallon":
                "X4_Diesel_Price"
        }
    )
    all_dfs.append(df_x4)

    # X5 – Rail freight price
    df_x5 = pd.read_csv(file_paths["X5"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x5 = df_x5[["PCU48214821"]].rename(columns={"PCU48214821": "X5_Rail_Price"})
    all_dfs.append(df_x5)

    # X6 – Disaster cost (alt-data)
    df_x6 = pd.read_csv(file_paths["X6"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x6 = df_x6[["CPI-Adjusted Cost"]].rename(columns={"CPI-Adjusted Cost": "X6_Disaster_Cost"})
    all_dfs.append(df_x6)

    # X7 – Hourly wage (labour)
    df_x7 = pd.read_csv(file_paths["X7"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x7 = df_x7[["CES0500000003"]].rename(columns={"CES0500000003": "X7_Hourly_Wage"})
    all_dfs.append(df_x7)

    # X8 – US scrap exports
    df_x8 = pd.read_csv(file_paths["X8"], parse_dates=["QuarterEnd"]).set_index("QuarterEnd")
    df_x8 = df_x8[["US_Scrap_Exports"]].rename(columns={"US_Scrap_Exports": "X8_Scrap_Exports"})
