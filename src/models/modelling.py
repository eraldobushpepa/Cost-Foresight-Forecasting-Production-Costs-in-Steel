def handle_missing_features(data, target_col="Y_Cost_Per_Ton"):
    """
    Impute les valeurs manquantes des features X avec IterativeImputer.
    Je laisse la cible Y intacte (je refuse de "fabriquer" le target).
    """
    print("\n--- 2. Handling Missing Feature Values ---")

    feature_cols = [c for c in data.columns if c != target_col]

    print("Missing values before imputation:")
    print(data[feature_cols].isna().sum())

    imputer = IterativeImputer(max_iter=10, random_state=42)
    features_imputed = imputer.fit_transform(data[feature_cols])

    features_imputed_df = pd.DataFrame(
        features_imputed,
        columns=feature_cols,
        index=data.index,
    )

    # Je recolle Y tel quel + les features imputées
    data_filled = pd.concat([data[[target_col]], features_imputed_df], axis=1)

    print("Missing values after imputation:")
    print(data_filled[feature_cols].isna().sum())

    return data_filled

def create_lagged_features(data, lag_periods, target_col="Y_Cost_Per_Ton"):
    """
    Crée les features décalées dans le temps (lags) pour toutes les colonnes X.

    Idée : pour prédire Y_t, je n'autorise que X_{t-1}, X_{t-2}, ...
    pour coller au fonctionnement réel (stocks / contrats).
    """
    print("\n--- 3. Engineering Lagged Features ---")

    feature_cols = [col for col in data.columns if col.startswith("X")]

    # Je travaille sur une copie pour ne pas modifier l'objet d'origine
    data_lagged = data.copy()

    for feature in feature_cols:
        for lag in lag_periods:
            col_name = f"{feature}_lag_{lag}Q"
            data_lagged[col_name] = data_lagged[feature].shift(lag)

    print(f"Created {len(feature_cols) * len(lag_periods)} lagged features.")

    # Je supprime les X non laggés pour ne pas "tricher" avec l'info du trimestre courant
    data_lagged = data_lagged.drop(columns=feature_cols)

    # Je coupe les premières lignes qui ont des NaN à cause des lags
    n_drop = max(lag_periods)
    final_data = data_lagged.iloc[n_drop:]

    print(f"Dropped first {n_drop} rows with incomplete lag information.")
    print(f"Final modelling dataset shape: {final_data.shape}")

    return final_data

def validate_model(X, y, model, n_splits=5):
    """
    Validation walk-forward avec TimeSeriesSplit.

    Je respecte la chronologie: les folds d'entraînement sont toujours
    antérieurs aux folds de test.
    """
    print(f"\n--- 4. Validating Model with TimeSeriesSplit (n_splits={n_splits}) ---")

    tscv = TimeSeriesSplit(n_splits=n_splits)

    mae_scores = []
    r2_scores = []

    for fold, (train_index, test_index) in enumerate(tscv.split(X), start=1):
        X_train, X_test = X.iloc[train_index], X.iloc[test_index]
        y_train, y_test = y.iloc[train_index], y.iloc[test_index]

        model.fit(X_train, y_train)
        y_pred = model.predict(X_test)

        mae = mean_absolute_error(y_test, y_pred)
        r2 = r2_score(y_test, y_pred)

        mae_scores.append(mae)
        r2_scores.append(r2)

        print(
            f"  Fold {fold}/{n_splits} | "
            f"Train: {len(y_train):3d} | Test: {len(y_test):3d} | "
            f"MAE: {mae:8.2f} | R²: {r2:6.3f}"
        )

    print("\n--- Cross-Validation Summary ---")
    print(f"Average MAE: {np.mean(mae_scores):.2f}")
    print(f"Average R²:  {np.mean(r2_scores):.3f}")

    return model

def get_feature_importance(model, X, y):
    """
    Entraîne le modèle sur tout le dataset et affiche le ranking
    des features les plus importantes.

    Ça me sert directement pour la partie "what drives Cost per Ton"
    dans le rapport.
    """
    print("\n--- 5. Training Final Model & Getting Feature Importance ---")

    model.fit(X, y)
    importances = model.feature_importances_

    feat_importance = (
        pd.Series(importances, index=X.columns)
        .sort_values(ascending=False)
    )

    print("\nTop 10 most important features:")
    print(feat_importance.head(10).to_string())

    return feat_importance

